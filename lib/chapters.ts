/**
 * Drops the "MOON 01"-style SKU code for display — customers see
 * "Wayfarer — Black", the code stays in `name`/`slug` for admin and
 * internal reference only.
 */
export function shortProductName(name: string) {
  return name.replace(/^MOON\s+\d+\s*/, "");
}

/**
 * Real photography lives as "<original stem>_no_bg.png" per product folder.
 */
export function chapterImageSrc(folder: string, file: string) {
  if (/^https?:\/\//.test(file)) return file;

  const dot = file.lastIndexOf(".");
  const stem = dot === -1 ? file : file.slice(0, dot);
  const resolved = `${stem}_no_bg.png`;
  return `/images/chapters/${encodeURIComponent(folder)}/${encodeURIComponent(resolved)}`;
}

/** Display order for grouping the catalogue by shape — matches the "five shapes" copy on-site. */
export const STYLE_ORDER = ["Wayfarer", "Round", "Rectangle", "Aviator", "Octagon"] as const;

/**
 * Every product name follows "MOON <n> <Shape> [(Material)] — <Rim> <Lens>",
 * e.g. "MOON 20 Aviator (Metal) — Gunmetal Brown" or
 * "MOON 06 Round — Demi-brown Blue Graded". Rim is always a single token
 * (the frame colourway), lens is everything after it (the tint name) — used
 * to group the homepage by shape and to power the collection explorer's
 * shape → rim colour → lens colour filters.
 */
export function styleRimLens(chapter: Chapter): { style: string; rim: string; lens: string } {
  // The "MOON <n>" code prefix is optional (admin-added products from
  // /admin/add-chapter don't get one), and a trailing "(descriptor)" —
  // e.g. "(Special Edition)" — is ignored rather than swallowed into lens.
  const match = chapter.name.match(
    /^(?:MOON\s+\d+\s+)?(\S+)(?:\s+\([^)]+\))?\s+—\s+(\S+)\s+(.+?)(?:\s+\([^)]+\))?$/
  );
  if (!match) return { style: "Other", rim: "", lens: "" };
  const [, style, rim, lens] = match;
  return { style, rim, lens };
}

/** Sorts chapters into STYLE_ORDER groups (unrecognized styles sink to the end), stable within each group. */
export function groupByStyle<T extends Chapter>(items: T[]): T[] {
  const rank = (c: T) => {
    const i = STYLE_ORDER.indexOf(styleRimLens(c).style as (typeof STYLE_ORDER)[number]);
    return i === -1 ? STYLE_ORDER.length : i;
  };
  return items
    .map((item, i) => ({ item, i }))
    .sort((a, b) => rank(a.item) - rank(b.item) || a.i - b.i)
    .map(({ item }) => item);
}

/**
 * Which tiles in a grid should open on their model face (the rest open on
 * product). Doesn't try to keep a strict product/model rhythm — it just
 * makes sure a grid never opens with every visible model the same gender by
 * coincidence of catalogue order. Walks the list in pairs, defaulting to
 * showing the second item of each pair (same rhythm as the old plain
 * alternation), but swaps to the first item of the pair instead whenever
 * the default choice would repeat the same gender as the last one shown.
 * Items with no known modelGender (no model photo yet) never show.
 */
export function pickDiverseModelFlips(items: Chapter[]): boolean[] {
  const flips = new Array(items.length).fill(false);
  let lastGender: string | undefined;

  for (let i = 0; i + 1 < items.length; i += 2) {
    const first = items[i];
    const second = items[i + 1];
    let chosenIndex: number | null = null;
    let chosenGender: string | undefined;

    if (second.modelGender && second.modelGender !== lastGender) {
      chosenIndex = i + 1;
      chosenGender = second.modelGender;
    } else if (first.modelGender && first.modelGender !== lastGender) {
      chosenIndex = i;
      chosenGender = first.modelGender;
    } else if (second.modelGender) {
      chosenIndex = i + 1;
      chosenGender = second.modelGender;
    } else if (first.modelGender) {
      chosenIndex = i;
      chosenGender = first.modelGender;
    }

    if (chosenIndex !== null) {
      flips[chosenIndex] = true;
      lastGender = chosenGender;
    }
  }

  return flips;
}
